 def test_new_xml_feature_fails_closed(self):
  from unittest.mock import patch
  old=e.read
  def changed(repo,path):return old(repo,path).replace('<path','<path android:trimPathStart="0.25"',1) if path.endswith('/ms_memory_24.xml') else old(repo,path)
  with patch.object(e,'read',side_effect=changed):
   with self.assertRaisesRegex(ValueError,'Unbound path attributes'):e.vectors(SOURCE)
 def test_stroke_paths_are_mapped_or_refused_never_dropped(self):
  # An original stroked path must either become Compose stroke output or be rejected as
  # unbound. Keeping only the fill path would silently lose the glyph outline.
  from unittest.mock import patch
  old=e.read
  def changed(repo,path):
   return old(repo,path).replace('<path','<path android:strokeColor="#00000000" android:strokeWidth="1.5"',1) if path.endswith('/ms_memory_24.xml') else old(repo,path)
  with patch.object(e,'read',side_effect=changed):
   try:body=e.vectors(SOURCE)
   except ValueError as error:
    self.assertIn('Unbound path attributes: ms_memory_24',str(error));return
  self.assertIn('stroke=SolidColor(Color(0x00000000))',body)
  self.assertIn('strokeLineWidth=1.5f',body)

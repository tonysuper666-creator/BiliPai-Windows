"""Reference model of the window bounds restore (desktop UX program, slice W3). No JVM, no network.

The Kotlin pure model is desktop/src/main/kotlin/com/bilipai/desktop/appearance/DesktopWindowsUxWindowBoundsModel.kt.
This module reads the section window_bounds of desktop-ux-contract.json and re-implements, line by line, what that file
decides:

  * plan(): the size, position and maximised state the window opens with, from the saved bounds, the monitors that
    exist now and the app zoom (planDesktopWindowsUxWindow);
  * Tracker: which bounds are worth saving, from samples of the window state (DesktopWindowsUxWindowTracker);
  * minimum_extent(): the smallest window extent for an app zoom (desktopWindowsUxMinimumExtent).

All numbers are AWT user space units, the units java.awt.Window reports. They equal the Compose dp of the window
state and are not scaled by the app zoom.

Integer arithmetic only. Python and Kotlin agree on every operation used here: sums, products of non negative
numbers, floor division of non negative numbers and min and max.

The golden rows of the contract are written by hand and are NOT regenerated by ux_model.py --write: they are an
oracle, so a change of this model that moves a row must be a visible, reviewed edit of the contract.

Run `python desktop/tools/ux/ux_window_model.py --check` to run every golden row through this model.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import ux_model as model  # noqa: E402

SECTION = "window_bounds"
APPEARANCE = model.REPO / "desktop/src/main/kotlin/com/bilipai/desktop/appearance"
MODEL_KT = APPEARANCE / "DesktopWindowsUxWindowBoundsModel.kt"
ADAPTER_KT = APPEARANCE / "DesktopWindowsUxWindowBounds.kt"

KINDS = ("DEFAULT", "UNVALIDATED", "KEPT", "ADJUSTED", "RELOCATED")
PLACEMENTS = ("FLOATING", "MAXIMIZED", "FULLSCREEN")


def section(contract=None):
    return (model.load() if contract is None else contract)[SECTION]


def bounds(x, y, width, height, maximized=False):
    return {"x": x, "y": y, "width": width, "height": height, "maximized": maximized}


def is_sane(contract, value):
    """DesktopWindowsUxWindowBounds.isSane: the sanity limits of the flags store (contract flags.window)."""
    limits = contract["flags"]["window"]
    low, high, origin = limits["min_extent"], limits["max_extent"], limits["max_abs_origin"]
    return (low <= value["width"] <= high and low <= value["height"] <= high
            and -origin <= value["x"] <= origin and -origin <= value["y"] <= origin)


def minimum_extent(contract, base, zoom_percent):
    """desktopWindowsUxMinimumExtent: base times the zoom percent (clamped to the zoom range), rounded half up."""
    zoom = contract["tokens"]["zoom_percent"]
    percent = min(max(zoom_percent, zoom["min"]), zoom["max"])
    return (base * percent + 50) // 100


def overlap_area(a, b):
    """desktopWindowsUxOverlapArea of two {x, y, width, height} rectangles."""
    width = min(a["x"] + a["width"], b["x"] + b["width"]) - max(a["x"], b["x"])
    height = min(a["y"] + a["height"], b["y"] + b["height"]) - max(a["y"], b["y"])
    return width * height if width > 0 and height > 0 else 0


def layout_screens(contract, name):
    """The monitors of a named layout of the contract, each {x, y, width, height, primary}."""
    return [dict(screen, primary=screen.get("primary", False)) for screen in section(contract)["layouts"][name]["screens"]]


def plan(contract, saved, screens, zoom_percent):
    """planDesktopWindowsUxWindow. saved is a bounds dict or None; screens a list of {x, y, width, height, primary}.
    Returns {kind, x, y, width, height, maximized, screen}; x, y and screen are None when not decided."""
    sec = section(contract)
    default_width, default_height = sec["default_size"]
    if saved is None or not is_sane(contract, saved):
        return {"kind": "DEFAULT", "x": None, "y": None, "width": default_width, "height": default_height,
                "maximized": False, "screen": None}
    min_width = minimum_extent(contract, sec["min_base"][0], zoom_percent)
    min_height = minimum_extent(contract, sec["min_base"][1], zoom_percent)
    candidates = [(index, screen) for index, screen in enumerate(screens) if screen["width"] > 0 and screen["height"] > 0]
    if not candidates:
        return {"kind": "UNVALIDATED", "x": None, "y": None, "width": max(saved["width"], min_width),
                "height": max(saved["height"], min_height), "maximized": saved["maximized"], "screen": None}
    best, best_area = None, 0
    for candidate in candidates:
        area = overlap_area(saved, candidate[1])
        if area > best_area:
            best, best_area = candidate, area
    vanished = best is None
    if best is not None:
        target = best
    else:
        primary = [candidate for candidate in candidates if candidate[1]["primary"]]
        target = primary[0] if primary else candidates[0]
    index, usable = target
    width = min(max(saved["width"], min_width), usable["width"])
    height = min(max(saved["height"], min_height), usable["height"])
    edge = sec["edge_tolerance"]
    right, bottom = usable["x"] + usable["width"], usable["y"] + usable["height"]
    if vanished:
        x = usable["x"] + (usable["width"] - width) // 2
        y = usable["y"] + (usable["height"] - height) // 2
    else:
        x = min(max(saved["x"], usable["x"] - edge), right + edge - width)
        y = min(max(saved["y"], usable["y"]), bottom + edge - height)
    if vanished:
        kind = "RELOCATED"
    elif (x, y, width, height) == (saved["x"], saved["y"], saved["width"], saved["height"]):
        kind = "KEPT"
    else:
        kind = "ADJUSTED"
    return {"kind": kind, "x": x, "y": y, "width": width, "height": height, "maximized": saved["maximized"],
            "screen": index}


def plan_bounds(result):
    """DesktopWindowsUxWindowPlan.bounds: the bounds once shown, or None while the platform picks the position."""
    if result["x"] is None or result["y"] is None:
        return None
    return bounds(result["x"], result["y"], result["width"], result["height"], result["maximized"])


def startup_seed(result, saved):
    """desktopWindowsUxStartup.seed: what the tracker starts from."""
    from_plan = plan_bounds(result)
    if from_plan is not None:
        return from_plan
    return saved if result["kind"] == "UNVALIDATED" else None


class Tracker:
    """DesktopWindowsUxWindowTracker."""

    def __init__(self, contract, seed):
        self.contract = contract
        self.floating = None
        self.maximized = False
        if seed is not None and is_sane(contract, seed):
            self.floating = (seed["x"], seed["y"], seed["width"], seed["height"])
            self.maximized = seed["maximized"]

    def accept(self, sample):
        if sample["minimized"]:
            return
        rect = (sample["x"], sample["y"], sample["width"], sample["height"])
        sane = is_sane(self.contract, bounds(*rect))
        if sample["placement"] == "FLOATING":
            if sane:
                self.floating = rect
                self.maximized = False
        elif sample["placement"] == "MAXIMIZED":
            self.maximized = True
            if self.floating is None and sane:
                self.floating = rect

    def bounds(self):
        if self.floating is None:
            return None
        value = bounds(*self.floating, self.maximized)
        return value if is_sane(self.contract, value) else None


def sample(placement, x, y, width, height, minimized=False):
    return {"placement": placement, "minimized": minimized, "x": x, "y": y, "width": width, "height": height}


def run_tracker(contract, seed, samples):
    tracker = Tracker(contract, seed)
    for item in samples:
        tracker.accept(item)
    return tracker.bounds()


def row_screens(contract, row):
    return layout_screens(contract, row["layout"])


def plan_row(contract, row):
    return plan(contract, row.get("saved"), row_screens(contract, row), row.get("zoom_percent", 125))


def expect_of(result):
    """The contract's spelling of a plan result."""
    return {"kind": result["kind"], "x": result["x"], "y": result["y"], "width": result["width"],
            "height": result["height"], "maximized": result["maximized"], "screen": result["screen"]}


def problems(contract=None):
    """Reasons why the golden rows of the contract disagree with this model. Empty means they all reproduce."""
    contract = model.load() if contract is None else contract
    sec = section(contract)
    found = []
    for row in sec["golden_plan"]:
        got = expect_of(plan_row(contract, row))
        if got != row["expect"]:
            found.append("golden_plan %s: model %s, contract %s" % (row["id"], got, row["expect"]))
    for row in sec["minimum_extent"]:
        got = [minimum_extent(contract, base, row["percent"]) for base in sec["min_base"]]
        if got != [row["width"], row["height"]]:
            found.append("minimum_extent %s: model %s, contract %s" % (row["percent"], got, [row["width"], row["height"]]))
    for row in sec["golden_tracker"]:
        got = run_tracker(contract, row.get("seed"), row["samples"])
        if got != row["expect"]:
            found.append("golden_tracker %s: model %s, contract %s" % (row["id"], got, row["expect"]))
    return found


def main(argv):
    found = problems()
    for line in found:
        print(line)
    if not found:
        print("window_bounds golden rows reproduce")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

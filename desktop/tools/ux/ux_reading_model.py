#!/usr/bin/env python3
"""Generate dynamic reading layout constants from the desktop UX contract."""
import sys
from pathlib import Path

import ux_model

KOTLIN_PATH = ux_model.REPO / "desktop/src/main/kotlin/com/bilipai/desktop/ui/DesktopDynamicReadingContract.kt"
FIELDS = (
    ("column_min", "DYNAMIC_READING_COLUMN_MIN"),
    ("column_max", "DYNAMIC_READING_COLUMN_MAX"),
    ("side_padding", "DYNAMIC_READING_SIDE_PADDING"),
    ("aside_gap", "DYNAMIC_READING_ASIDE_GAP"),
    ("aside_width", "DYNAMIC_READING_ASIDE_WIDTH"),
    ("aside_from_content_width", "DYNAMIC_READING_ASIDE_FROM_WIDTH"),
)
HEADER = ('// Generated by desktop/tools/ux/ux_reading_model.py --write from '
          'desktop-ux-contract.json ("reading.dynamic"). Do not edit; edit the contract and rerun.')


def render(contract):
    reading = contract.get("reading") if isinstance(contract, dict) else None
    dynamic = reading.get("dynamic") if isinstance(reading, dict) else None
    lines = [HEADER, "package com.bilipai.desktop.ui", ""]
    for key, name in FIELDS:
        value = dynamic.get(key) if isinstance(dynamic, dict) else None
        if type(value) is not int:
            raise ValueError(f"reading.dynamic.{key} must be an int")
        lines.append(f"internal const val {name} = {value}")
    return "\n".join(lines) + "\n"


def problems(contract_path=ux_model.CONTRACT_PATH, kotlin_path=KOTLIN_PATH):
    try:
        expected = render(ux_model.load(contract_path)).encode("utf-8")
        actual = Path(kotlin_path).read_bytes()
    except (OSError, ValueError, UnicodeError) as error:
        return [str(error)]
    if actual != expected:
        return ["generated dynamic reading constants are stale (run ux_reading_model.py --write)"]
    return []


def write():
    ux_model.write()
    KOTLIN_PATH.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN_PATH.write_bytes(render(ux_model.load()).encode("utf-8"))


def main(argv):
    if "--write" in argv:
        write()
        print("contract, Kotlin test copy and dynamic reading constants rewritten")
        return 0
    found = problems()
    for line in found:
        print(line)
    if not found:
        print("dynamic reading constants are in sync")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
